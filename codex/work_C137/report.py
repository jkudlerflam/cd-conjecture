"""Assemble TABLES.md from results/. Window constants K = n^2 (e0 - lambda)/M.
For bonds with exact e0 (literature formulas) a single number is reported. For random bonds
the bracket [n^2 (e0_low - lambda)/M, n^2 (e0_up - lambda)/M] uses e0_up from iTEBD (a TI state
on Z) and e0_low = the best certified lower bound available (max over computed windows of
the window value, which is <= E_LTI <= e0)."""
import json, glob, warnings
warnings.filterwarnings('ignore')
import numpy as np
from common import HERE, gauge_M
import models

R = HERE / 'results'
lines = ['# C137 tables (generated by report.py)', '']


def load_survey(name):
    recs = {}
    for f in [R / f'{name}.json'] + sorted(glob.glob(str(R / f'{name}_n*.json'))) + sorted(glob.glob(str(R / 'typhon' / f'{name}*.json'))):
        try:
            for r in json.load(open(f)):
                recs[r['n']] = r
        except Exception:
            pass
    return [recs[n] for n in sorted(recs)]


def load_rings(name):
    out = {}
    for f in [R / 'rings' / f'{name}.json'] + sorted(glob.glob(str(R / 'rings' / f'{name}_L*.json'))) + sorted(glob.glob(str(R / 'typhon' / 'rings' / f'{name}*.json'))):
        try:
            out.update({int(k): v for k, v in json.load(open(f)).items()})
        except Exception:
            pass
    return out


Mcache = {}
def Mof(h):
    key = h.tobytes()
    if key not in Mcache:
        Mcache[key] = gauge_M(h)['M_up']
    return Mcache[key]


summary = {}
main = ['Heisenberg', 'XX', 'XXZ_0.5', 'XXZ_2', 'XXZ_-0.9', 'XXZ_-0.99', 'TFIM_1', 'TFIMc-2', 'TFIMc0.5', 'TFIMc5', 'chiral']
lines += ['## Main bonds (exact e0)', '',
          'Ring column only at even n (odd antiferromagnetic rings are frustrated and E_n/n > e_0 there). Columns: K for the optimal window (c and u optimized), the sine-square window with optimized u, the C135 sine window with optimized u, both fixed windows with u = 0 in the stated representative, the ring constant n^2(e0 - E_n/n)/M, and the a-posteriori bundle gap of the optimum.', '']
for name in main:
    S = load_survey(name)
    if not S:
        continue
    rings = load_rings(name)
    lines += [f'### {name}', '', '| n | opt | ssd_u | sine_u | ssd_0 | sine_0 | ring | gap |', '| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
    rows = []
    for r in S:
        n = r['n']; m = models.get(name, n); M = Mof(m['h']); e0 = r['e0_exact']
        K = lambda v: n * n * (e0 - v) / M
        ring = K(rings[n]) if (n in rings and n % 2 == 0) else float('nan')
        row = dict(n=n, opt=K(r['opt']['value']), ssd_u=K(r['ssd_u']['value']), sine_u=K(r['sine_u']['value']),
                   ssd_0=K(r['ssd_0']['value']), sine_0=K(r['sine_0']['value']), ring=ring, gap=r['opt']['pred_gap'], c=r['opt']['c'])
        rows.append(row)
        lines.append('| %d | %.4f | %.4f | %.4f | %.4f | %.4f | %.4f | %.0e |' % (n, row['opt'], row['ssd_u'], row['sine_u'], row['ssd_0'], row['sine_0'], ring, row['gap']))
    summary[name] = rows
    lines.append('')

# random bonds
mps = {}
for f in glob.glob(str(R / 'e0_mps' / '*.json')):
    d = json.load(open(f)); mps[d['key']] = d['e0_up']
lines += ['## Random bonds on the M = 1 sphere (C135 seed 1352026)', '',
          'Entries at the largest computed n: K_opt, K_ssd_u, K_sine_u as brackets [lower, upper] from e0_low (best window value over all n computed) and e0_up (iTEBD chi = 64, symmetrized). The column d_opt-ssd = n^2 (W_opt - W_ssd_u)/M needs no e0. Also max over n of the upper K_opt.', '',
          '| bond | n | K_opt | K_ssd_u | K_sine_u | n^2(opt-ssd)/M | n^2(opt-sine)/M | max_n K_opt_up | ring K_up at n (even) |',
          '| :--- | ---: | :--- | :--- | :--- | ---: | ---: | ---: | ---: |']
rand_rows = []
for i in range(30):
    name = f'random_{i:02d}'
    S = load_survey(name)
    if not S:
        continue
    m = models.get(name); M = Mof(m['h'])
    e0_low = max(r['opt']['value'] for r in S)
    e0_up = mps.get(name, float('nan'))
    r = S[-1]; n = r['n']
    br = lambda v: '[%.3f, %.3f]' % (n * n * (e0_low - v) / M, n * n * (e0_up - v) / M)
    maxK = max(rr['n'] ** 2 * (e0_up - rr['opt']['value']) / M for rr in S)
    rings = load_rings(name)
    ne = n if n % 2 == 0 else n - 1
    ringK = ne * ne * (e0_up - rings[ne]) / M if ne in rings else float('nan')
    d1 = n * n * (r['opt']['value'] - r['ssd_u']['value']) / M
    d2 = n * n * (r['opt']['value'] - r['sine_u']['value']) / M
    rand_rows.append(dict(name=name, n=n, e0_low=e0_low, e0_up=e0_up, Kopt_up=n * n * (e0_up - r['opt']['value']) / M,
                          Kssd_up=n * n * (e0_up - r['ssd_u']['value']) / M, Ksine_up=n * n * (e0_up - r['sine_u']['value']) / M,
                          d_ssd=d1, d_sine=d2, maxK=maxK, ringK=ringK,
                          per_n=[dict(n=rr['n'], opt=rr['opt']['value'], ssd_u=rr['ssd_u']['value'], sine_u=rr['sine_u']['value'],
                                      ssd_0=rr['ssd_0']['value'], sine_0=rr['sine_0']['value']) for rr in S]))
    if e0_up < e0_low - 1e-9: print('WARNING bracket reversed', name, e0_low, e0_up)
    lines.append('| %s | %d | %s | %s | %s | %.4f | %.4f | %.3f | %.3f |' % (name, n, br(r['opt']['value']), br(r['ssd_u']['value']), br(r['sine_u']['value']), d1, d2, maxK, ringK))
summary['random'] = rand_rows
lines.append('')

# lesson 2, free TFIM
for tag in ['A', 'B']:
    f = R / f'lesson2_free_{tag}.json'
    if not f.exists():
        continue
    L2 = json.load(open(f))
    lines += [f'## Lesson 2, free TFIM at g = 1 + c/n (run {tag})', '', '| c | n | opt | ssd_u | sine_u | ssd_0 | ssd_site | sine (u = 0, Theorem Q window) |', '| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
    for r in L2:
        g = lambda k: ('%.4f' % r[k]) if k in r else 'NA'
        lines.append('| %g | %d | %s | %s | %s | %s | %s | %s |' % (r['c'], r['n'], g('K_opt'), g('K_ssd_u'), g('K_sine_u'), g('K_ssd_0'), g('K_ssd_site'), g('K_sine_v2')))
    lines.append('')

# lesson 2, XYZ
for c in ['0.5', '2.0', '5.0']:
    f = R / f'xyz_c{c}.json'
    if not f.exists():
        continue
    X = json.load(open(f))
    lines += [f'## Lesson 2, interacting XYZ (Delta = 0.5, gamma = {c}/n)', '',
              'D_ssd = n^2 (W_opt - W_ssd)/M and D_sine = n^2 (W_opt - W_sine)/M need no e0. K_up uses e0_up from iTEBD where available.', '',
              '| n | gamma | D_ssd | D_sine | K_opt_up |', '| ---: | ---: | ---: | ---: | ---: |']
    for r in X:
        n = r['n']; h = models.xyz(1 + r['gam'], 1 - r['gam'], 0.5) if hasattr(models, 'xyz') else None
        from common import xyz
        M = Mof(xyz(1 + r['gam'], 1 - r['gam'], 0.5))
        key = f'xyz_c{float(c)}_n{n}'
        Kup = n * n * (mps[key] - r['opt']) / M if key in mps else float('nan')
        lines.append('| %d | %.4f | %.4f | %.4f | %.4f |' % (n, r['gam'], n * n * (r['opt'] - r['ssd']) / M, n * n * (r['opt'] - r['sine']) / M, Kup))
    lines.append('')

(HERE / 'TABLES.md').write_text('\n'.join(lines) + '\n')
(HERE / 'results' / 'summary.json').write_text(json.dumps(summary, indent=1, default=float))
print('\n'.join(lines))
