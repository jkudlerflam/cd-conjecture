import os
os.environ['OPENBLAS_NUM_THREADS']='1'
import numpy as np
import scipy.linalg as la
from scipy.optimize import brentq
from reduced import Reduced
from scan import roots
import json
out=[]
for n,asym,phi in [(2,.05,.001),(3,.001,1e-5),(4,1e-5,1e-7)]:
 T0,M0=Reduced(n).leading();s=la.eigvalsh(-(T0.real+T0.real.T)/2)
 Traw,Mraw=Reduced(n,1+asym,phi).leading();T=Traw.real;M=1j*(Mraw.imag-Mraw.imag.T)/2
 mu=.3*s[0];M+=mu*np.eye(n);rr=roots(T,M)
 A=-(T+T.T)/2;e,U=la.eigh(A);W=(U/np.sqrt(e))@U.T;t=W@T@W;m=W@M@W
 refined=[]
 for k in rr['p']:
  ev=la.eigvalsh(m+t*np.exp(1j*k)+t.T*np.exp(-1j*k));ix=np.argmin(abs(ev))
  def f(x):return la.eigvalsh(m+t*np.exp(1j*x)+t.T*np.exp(-1j*x))[ix]
  dk=min(rr['delta2']/10,1e-4)
  refined.append(brentq(f,k-dk,k+dk,xtol=5e-15))
 err=max(abs(np.array(refined)-rr['p']))
 delta0=1-.9*(1+asym);b=1.25;eta=.01
 margin=min(rr['delta2']/8,rr['delta4']/16,1.)
 vmin=min(abs(np.array(rr['v'])))
 tau2=eta*vmin*margin*delta0**5/(8*b*b)
 lam=eta*vmin*margin*delta0**4/(12*b**3)
 row=dict(n=n,asym=asym,phi=phi,mu=mu,symmetric_eigenvalues=s.tolist(),ratio=s[0]/s[-1],T_max=float(la.norm(T,2)),
          symmetry_error_T=float(la.norm(Traw-T,2)),symmetry_error_M=float(la.norm(Mraw-1j*(Mraw.imag-Mraw.imag.T)/2,2)),
          independent_root_error=err,delta0=delta0,tau=np.sqrt(tau2),lambda_bare=lam,Wmax=lam*lam*tau2*la.norm(T,2),E_osc=lam*lam*tau2*vmin*min(rr['delta2'],rr['delta4']),**rr)
 out.append(row);print(json.dumps(row),flush=True)
json.dump(out,open('verified_targets.json','w'),indent=2)
# Independent full occupation-space checks, already generated by leading_full.py.
for n in [2,4]:
 ref=np.load('full_leading_n%d.npz'%n);T,M=Reduced(n,1.05,.001).leading()
 print('full comparison',n,'T',la.norm(T-ref['T'])/la.norm(T),'Mimag',la.norm(M.imag-ref['M'].imag)/la.norm(M.imag))

# Cross-check the actual n=4 target against the full occupation calculation.
ref=np.load('full_target_n4.npz');rr=out[-1]
Tf=ref['T'].real;Mf=1j*(ref['M'].imag-ref['M'].imag.T)/2+rr['mu']*np.eye(4)
rf=roots(Tf,Mf)
comparison=dict(root_difference=float(max(abs(np.array(rf['p'])-rr['p']))),centre_difference=float(max(abs(np.array(rf['centres'])-rr['centres']))),full_result=rf)
json.dump(comparison,open('full_target_comparison.json','w'),indent=2)
print('full target comparison',comparison['root_difference'],comparison['centre_difference'],rf['delta4'])
