#!/usr/bin/env python3
"""Question (3): a two-port cell whose second-order logical bond is an incommensurate free-fermion
(XX chain in a field) target, and its exact logical chain at finite coupling.

Target bond on logical qubits:  K = X X + Y Y + hz (Z 1 + 1 Z),  hz = 0.6, so that the logical chain
sum_j K_{j,j+1} is free fermions with eps(k) = 4 cos k + 4 hz and Fermi momentum arccos(-hz),
incommensurate, c = 1.  The cell is cell.build_twoport(K, 2) (D = 32, the C8 geometry).
For each lam the exact two- and three-cell Schrieffer-Wolff terms are computed (sw_cluster.heff),
normalized by the hopping scale tau^2 lam^2, split into U(1)-symmetric and U(1)-breaking parts
(U(1) generated by sum Z), and saved as data/ff_lam*.npz for effchain.py (model file:...).
Written by Claude (Opus 5.5) for contrib/routeA_numerics, 2026-10-27.
"""
import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import numpy as np
from cell import build_twoport, PAULI, second_order
from sw_cluster import heff

X, Y, Z = PAULI
I2 = np.eye(2)
HZ = 0.6
K = np.kron(X, X) + np.kron(Y, Y) + HZ * (np.kron(Z, I2) + np.kron(I2, Z))


def u1_split(h, n):
    """Part of h commuting with sum_j Z_j (dephasing average over the U(1)) and the rest."""
    Zt = sum(np.kron(np.kron(np.eye(2 ** j), Z), np.eye(2 ** (n - j - 1))) for j in range(n))
    m = np.real(np.diag(Zt))
    mask = (np.abs(m[:, None] - m[None, :]) < 1e-9)
    return h * mask, h * (~mask)


def main():
    cell = build_twoport(K, 2)
    tau2 = cell['tau'] ** 2
    e2 = second_order(cell)
    out = dict(D=cell['D'], tau2=tau2, second_order_error=float(np.linalg.norm(e2 - cell['pred2'])), rows=[])
    for lam in [0.02, 0.05, 0.1, 0.2]:
        h2, i2 = heff(cell, 2, lam)
        H3, i3 = heff(cell, 3, lam)
        h3 = H3 - np.kron(h2, I2) - np.kron(I2, h2)
        s = tau2 * lam ** 2
        h2n = (h2 - np.trace(h2) / 4 * np.eye(4)) / s
        h3n = (h3 - np.trace(h3) / 8 * np.eye(8)) / s
        sym2, brk2 = u1_split(h2n, 2)
        sym3, brk3 = u1_split(h3n, 3)
        # largest U(1)-breaking pieces: pairing (XX - YY, XY + YX) and transverse fields
        c = lambda A, B: np.trace(np.kron(A, B) @ h2n).real / 4
        row = dict(lam=lam, hop_XX=c(X, X), hop_YY=c(Y, Y), ZZ=c(Z, Z), fieldL=c(Z, I2), fieldR=c(I2, Z),
                   pair_gamma=(c(X, X) - c(Y, Y)) / 2, pair_XY=(c(X, Y) + c(Y, X)) / 2,
                   transverse=[c(X, I2), c(Y, I2), c(I2, X), c(I2, Y)],
                   brk2=float(np.linalg.norm(brk2, 2)), brk3=float(np.linalg.norm(brk3, 2)),
                   h3=float(np.linalg.norm(h3n, 2)), next2=i2['next'], next3=i3['next'])
        out['rows'].append(row)
        print(json.dumps(row), flush=True)
        hfull = np.kron(h2n, I2) + h3n
        np.savez(os.path.join(HERE, 'data', f'ff_lam{lam}.npz'), h=hfull, r=3, d=2, hb=h2n, h2=h2, h3=h3)
        hsym = np.kron(sym2, I2) + sym3
        np.savez(os.path.join(HERE, 'data', f'ffsym_lam{lam}.npz'), h=hsym, r=3, d=2, hb=sym2)
    # the bare target, for calibration
    np.savez(os.path.join(HERE, 'data', 'ff_target.npz'), h=K - np.trace(K) / 4 * np.eye(4), r=2, d=2)
    json.dump(out, open(os.path.join(HERE, 'data', 'ff_terms.json'), 'w'), indent=1)


if __name__ == '__main__':
    main()
