#!/usr/bin/env python3
"""Closed-book C6 calculations. Pauli normalization, periodic one-site TI bonds.

No project files are read. Only c6_* outputs generated by this script are read.
Examples:
  python3 c6.py check
  python3 c6.py scan --lengths 10 12 14 --D 0.1 --fields 1.7 1.9 2.1
  python3 c6.py run --model ising --lengths 12 16 20
  python3 c6.py run --model residual --field 1.9 --D .1 --lengths 16 20 22 --towers

The momentum basis contains every translation orbit compatible with momentum.
Parity, when selected, means (-1)^number_of_down_spins, with Z|0>=|0>.
T rotates bits left and has eigenvalue exp(+2 pi i m/L).
"""
