START = time.monotonic()
OUTPUT = Path('c6_results.jsonl')


def record(data):
    data['code_version'] = 2
    data['elapsed_s'] = round(time.monotonic() - START, 3)
    with OUTPUT.open('a') as f:
        f.write(json.dumps(data) + '\n')
    print(json.dumps(data), flush=True)


@njit
def popcount(s):
    n = 0
    while s:
        s &= s - 1
        n += 1
    return n


@njit
def translation_orbits(L, parity):
    N = 1 << L
    mask = N - 1
    ids = np.full(N, -1, np.int32)
    shifts = np.zeros(N, np.int8)
    reps = np.empty(N, np.int32)
    periods = np.empty(N, np.int8)
    n = 0
    for s in range(N):
        if ids[s] >= 0:
            continue
        if parity >= 0 and popcount(s) % 2 != parity:
            continue
        reps[n] = s
        t, p = s, 0
        while True:
            ids[t] = n
            shifts[t] = p
            p += 1
            t = ((t << 1) & mask) | (t >> (L - 1))
            if t == s:
                break
        periods[n] = p
        n += 1
    return ids, shifts, reps[:n].copy(), periods[:n].copy()


@njit
def fill_matrix(L, m, J, h, ids, shifts, reps, periods, selected, sector):
    dim = len(selected)
    rows = np.empty(dim * (3 * L + 1), np.int32)
    cols = np.empty(dim * (3 * L + 1), np.int32)
    vals = np.empty(dim * (3 * L + 1), np.complex128)
    phases = np.exp(2j * np.pi * m * np.arange(L) / L)
    used = 0
    for col in range(dim):
        a = selected[col]
        s = reps[a]
        p = periods[a]
        diagonal = 0.0
        for i in range(L):
            j = (i + 1) % L
            zi = 1 - 2 * ((s >> i) & 1)
            zj = 1 - 2 * ((s >> j) & 1)
            diagonal += J[2, 2] * zi * zj + h[2] * zi
            amp = J[0, 0] - J[1, 1] * zi * zj + 1j * (J[0, 1] * zj + J[1, 0] * zi)
            target = s ^ (1 << i) ^ (1 << j)
            b = ids[target]
            if abs(amp) > 1e-15 and b >= 0 and sector[b] >= 0:
                rows[used], cols[used] = sector[b], col
                vals[used] = amp * np.sqrt(p / periods[b]) * phases[shifts[target]]
                used += 1
            amp = J[0, 2] * zj + 1j * J[1, 2] * zi * zj + h[0] + 1j * h[1] * zi
            target = s ^ (1 << i)
            b = ids[target]
            if abs(amp) > 1e-15 and b >= 0 and sector[b] >= 0:
                rows[used], cols[used] = sector[b], col
                vals[used] = amp * np.sqrt(p / periods[b]) * phases[shifts[target]]
                used += 1
            amp = J[2, 0] * zi + 1j * J[2, 1] * zi * zj
            target = s ^ (1 << j)
            b = ids[target]
            if abs(amp) > 1e-15 and b >= 0 and sector[b] >= 0:
                rows[used], cols[used] = sector[b], col
                vals[used] = amp * np.sqrt(p / periods[b]) * phases[shifts[target]]
                used += 1
        rows[used], cols[used], vals[used] = col, col, diagonal
        used += 1
    return rows[:used], cols[:used], vals[:used]


@njit
def expand_vector(L, m, ids, shifts, periods, sector, v):
    out = np.zeros(1 << L, np.complex128)
    phases = np.exp(-2j * np.pi * m * np.arange(L) / L)
    for s in range(1 << L):
        a = ids[s]
        if a >= 0 and sector[a] >= 0:
            out[s] = v[sector[a]] * phases[shifts[s]] / np.sqrt(float(periods[a]))
    return out


class Sector:
    def __init__(self, L, m, parity, orbit_data=None):
        self.L, self.m, self.parity = L, m % L, parity
        self.data = orbit_data if orbit_data is not None else translation_orbits(L, parity)
        ids, shifts, reps, periods = self.data
        self.selected = np.flatnonzero((periods.astype(np.int32) * self.m) % L == 0).astype(np.int32)
        self.sector = np.full(len(reps), -1, np.int32)
        self.sector[self.selected] = np.arange(len(self.selected), dtype=np.int32)

    def matrix(self, J, h):
        if self.parity >= 0:
            odd = abs(h[0]) + abs(h[1]) + np.abs(J[:2, 2]).sum() + np.abs(J[2, :2]).sum()
            if odd > 1e-14:
                raise ValueError('Parity is not conserved for these parameters')
        r, c, v = fill_matrix(self.L, self.m, J, h, *self.data, self.selected, self.sector)
        H = sparse.coo_matrix((v, (r, c)), shape=(len(self.selected),) * 2).tocsr()
        H.eliminate_zeros()
        if np.max(np.abs(H.data.imag), initial=0) < 1e-13:
            H = H.real.tocsr()
        return H

    def expand(self, vector):
        ids, shifts, reps, periods = self.data
        return expand_vector(self.L, self.m, ids, shifts, periods, self.sector, vector)


def solve(sec, J, h, n=4, vector=False):
    H = sec.matrix(J, h)
    n = min(n, H.shape[0] - 1)
    if H.shape[0] < 50:
        e, v = np.linalg.eigh(H.toarray())
        e, v = e[:n], v[:, :n]
    else:
        rng = np.random.default_rng(112358 + sec.L + sec.m)
        v0 = rng.normal(size=H.shape[0])
        if np.iscomplexobj(H.data):
            v0 = v0 + 1j * rng.normal(size=H.shape[0])
        e, v = eigsh(H, k=n, which='SA', tol=3e-11, maxiter=12000,
                     ncv=max(30, 3 * n + 5), v0=v0)
        order = np.argsort(e)
        e, v = e[order], v[:, order]
    residual = max(float(np.linalg.norm(H @ v[:, i] - e[i] * v[:, i])) for i in range(len(e)))
    return e, (v[:, 0] if vector else None), residual, H.shape[0]


def entropies(psi, L, all_cuts=True):
    cuts = range(2, L // 2 + 1) if all_cuts else [L // 2]
    result = {}
    for l in cuts:
        a = psi.reshape((1 << (L - l), 1 << l))
        rho = a.conj().T @ a
        p = np.linalg.eigvalsh(rho)
        p = p[p > 1e-14]
        result[str(l)] = float(-np.dot(p, np.log(p)))
    return result


def parameters(model, field, D, tilt=1.):
    if model == 'ising':
        return np.diag([-1., 0., 0.]), np.array([0., 0., -1.])
    if model == 'xx':
        return np.diag([-1., -1., 0.]), np.zeros(3)
    if model == 'residual':
        J = np.diag([-1., -.5, .25])
        J[0, 1], J[1, 0] = D, -D
        return J, np.array([0., 0., -field])
    if model == 'generic':
        J = np.diag([-1., -.5, .25])
        # D=(.07,.11,D), J_ab = epsilon_abc D_c.
        J[0, 1], J[1, 0] = D, -D
        J[1, 2], J[2, 1] = .07 * tilt, -.07 * tilt
        J[2, 0], J[0, 2] = .11 * tilt, -.11 * tilt
        return J, np.array([.08 * tilt, .06 * tilt, -field])
    raise ValueError(model)


def run(args):
    if args.model == 'ising':
        args.field, args.D = 1., 0.
    elif args.model == 'xx':
        args.field, args.D = 0., 0.
    J, h = parameters(args.model, args.field, args.D, args.tilt)
    for L in args.lengths:
        ground = None
        parities = [-1] if args.model == 'generic' else [0, 1]
        for parity in parities:
            orbit_data = translation_orbits(L, parity)
            momenta = sorted(set([0, 1, L - 1, 2, L - 2, L // 2])) if args.towers else [0]
            if args.all_momenta:
                momenta = list(range(L))
            for m in momenta:
                sec = Sector(L, m, parity, orbit_data)
                e, v, residual, dim = solve(sec, J, h, n=args.levels, vector=True)
                record(dict(kind='spectrum', model=args.model, L=L, parity=parity, m=m,
                            field=args.field, D=args.D, tilt=args.tilt if args.model == 'generic' else 0.,
                            energies=e.tolist(), residual=residual, dim=dim))
                if ground is None or e[0] < ground[0] - 1e-9:
                    ground = (e[0], parity, m, sec.expand(v))
            del orbit_data
        e0, parity, m, psi = ground
        S = entropies(psi, L, all_cuts=not args.half_only)
        fit_c = None
        if len(S) >= 3:
            cuts = np.array([int(k) for k in S if int(k) >= max(3, L // 4)])
            chord = np.log(L / np.pi * np.sin(np.pi * cuts / L))
            fit_c = float(3 * np.polyfit(chord, [S[str(i)] for i in cuts], 1)[0])
        record(dict(kind='ground', model=args.model, L=L, field=args.field, D=args.D,
                    tilt=args.tilt if args.model == 'generic' else 0.,
                    energy=float(e0), parity=parity, m=m, entropies=S, c_chord=fit_c,
                    momentum_coverage='all' if args.all_momenta else ('selected' if args.towers else 'k=0 only')))


def scan(args):
    for L in args.lengths:
        sectors = [Sector(L, 0, parity) for parity in [0, 1]]
        for field in args.fields:
            J, h = parameters('residual', field, args.D)
            energies = [solve(sec, J, h, n=1)[0][0] for sec in sectors]
            record(dict(kind='scan', L=L, D=args.D, field=field,
                        even=float(energies[0]), odd=float(energies[1]),
                        scaled_gap=float(L * (energies[1] - energies[0]))))


def sweep(args):
    """All-momentum ground-state screening, not a claim of criticality."""
    for L in args.lengths:
        parities = [-1] if args.model == 'generic' else [0, 1]
        sectors = []
        for parity in parities:
            data = translation_orbits(L, parity)
            sectors.extend(Sector(L, m, parity, data) for m in range(L))
        for D in args.Ds:
            for field in args.fields:
                J, h = parameters(args.model, field, D, args.tilt)
                best, spectrum, max_residual = None, [], 0.
                for sec in sectors:
                    e, v, residual, dim = solve(sec, J, h, n=1, vector=True)
                    spectrum.append([sec.parity, sec.m, float(e[0])])
                    max_residual = max(max_residual, residual)
                    if best is None or e[0] < best[0] - 1e-9:
                        best = (e[0], sec, v)
                e, sec, v = best
                S = entropies(sec.expand(v), L)
                cuts = np.arange(max(3, L // 4), L // 2 + 1)
                chord = np.log(L / np.pi * np.sin(np.pi * cuts / L))
                c = float(3 * np.polyfit(chord, [S[str(i)] for i in cuts], 1)[0])
                record(dict(kind='sweep', model=args.model, L=L, field=field, D=D,
                            tilt=args.tilt if args.model == 'generic' else 0.,
                            energy=float(e), parity=sec.parity, m=sec.m, entropies=S,
                            c_chord=c, sector_minima=spectrum, residual=max_residual,
                            momentum_coverage='all'))


def tune(args):
    sectors = {L: [Sector(L, 0, p) for p in [0, 1]] for L in args.lengths}
    def fn(field):
        J, h = parameters('residual', field, args.D)
        gaps = []
        for L in args.lengths:
            e = [solve(sec, J, h, n=1)[0][0] for sec in sectors[L]]
            gaps.append(L * (e[1] - e[0]))
        difference = gaps[-1] - gaps[0]
        record(dict(kind='tune_step', lengths=args.lengths, field=field, D=args.D,
                    scaled_gaps=gaps, difference=difference))
        return difference
    root = brentq(fn, *args.bracket, xtol=2e-7)
    record(dict(kind='tune_result', lengths=args.lengths, D=args.D, field=root))


def crossing(args):
    """Track a specified pair of momentum sectors, not an exhaustive phase boundary."""
    for L in args.lengths:
        m = round(L / 3)
        data = translation_orbits(L, -1)
        secs = [Sector(L, q, -1, data) for q in [0, m]]
        def fn(tilt):
            J, h = parameters('generic', args.field, args.D, tilt)
            e = [solve(sec, J, h, n=1)[0][0] for sec in secs]
            return e[1] - e[0]
        root = brentq(fn, *args.bracket, xtol=2e-7)
        J, h = parameters('generic', args.field, args.D, root)
        J0, h0 = parameters('generic', args.field, args.D, 0.)
        J1, h1 = parameters('generic', args.field, args.D, 1.)
        branches = []
        for sec in secs:
            e, v, residual, dim = solve(sec, J, h, n=2, vector=True)
            derivative = float(np.vdot(v, sec.matrix(J1-J0, h1-h0) @ v).real / L)
            reps = sec.data[2][sec.selected]
            N = np.array([int(s).bit_count() for s in reps], float)
            density = float(np.dot(np.abs(v)**2, N) / L)
            entropy = entropies(sec.expand(v), L, all_cuts=False)[str(L//2)]
            branches.append(dict(m=sec.m, energies=e.tolist(), derivative_per_site=derivative,
                                 down_density=density, half_entropy=entropy, residual=residual))
        record(dict(kind='crossing_result', model='generic', L=L, D=args.D, field=args.field,
                    tilt=root, branches=branches, coverage='two specified momentum sectors'))


def crossing_dispersion():
    records = [json.loads(line) for line in OUTPUT.read_text().splitlines() if line.strip()]
    roots = {r['L']:r for r in records if r['kind'] == 'crossing_result'}
    for L, r in sorted(roots.items()):
        J, h = parameters('generic', r['field'], r['D'], r['tilt'])
        data = translation_orbits(L, -1)
        energies = []
        residuals = []
        for m in range(L):
            e, v, error, dim = solve(Sector(L,m,-1,data), J,h,n=1)
            energies.append(float(e[0]))
            residuals.append(error)
        m = round(L/3)
        curvature = (energies[(m+1)%L]+energies[(m-1)%L]-2*energies[m])/(2*np.pi/L)**2
        record(dict(kind='crossing_dispersion', L=L, field=r['field'], D=r['D'], tilt=r['tilt'],
                    sector_minima=energies, proposed_m=m, minimum_m=int(np.argmin(energies)),
                    center_above_min=energies[m]-min(energies), curvature=curvature,
                    adjacent_gaps=[energies[(m+q)%L]-energies[m] for q in [-1,1]],
                    residual=max(residuals), coverage='all momenta'))


def dense_independent(L, J, h):
    paulis = [np.array([[0, 1], [1, 0]]), np.array([[0, -1j], [1j, 0]]), np.diag([1, -1])]
    eye = np.eye(2)
    def product(operators):
        out = np.ones((1, 1))
        for i in reversed(range(L)):
            out = np.kron(out, operators.get(i, eye))
        return out
    H = np.zeros((1 << L, 1 << L), complex)
    for i in range(L):
        for a in range(3):
            H += h[a] * product({i: paulis[a]})
            for b in range(3):
                H += J[a, b] * product({i: paulis[a], (i + 1) % L: paulis[b]})
    return H


def check():
    rng = np.random.default_rng(81)
    L = 6
    J, h = rng.normal(size=(3, 3)), rng.normal(size=3)
    H = dense_independent(L, J, h)
    exact = np.linalg.eigvalsh(H)
    values = []
    herm = 0.
    intertwine = 0.
    data = translation_orbits(L, -1)
    for m in range(L):
        sec = Sector(L, m, -1, data)
        block = sec.matrix(J, h).toarray()
        herm = max(herm, float(np.max(np.abs(block - block.conj().T))))
        values.extend(np.linalg.eigvalsh(block))
        v = rng.normal(size=len(block)) + 1j * rng.normal(size=len(block))
        intertwine = max(intertwine, float(np.linalg.norm(H @ sec.expand(v) - sec.expand(block @ v))))
    error = float(np.max(np.abs(exact - np.sort(values))))
    print(dict(spectral_error=error, hermiticity_error=herm, intertwining_error=intertwine), flush=True)
    assert error < 1e-10 and herm < 1e-10 and intertwine < 1e-10
    J, h = parameters('ising', 0, 0)
    values = []
    for p in [0, 1]:
        for m in range(L):
            sec = Sector(L, m, p)
            values.extend(np.linalg.eigvalsh(sec.matrix(J, h).toarray()))
    parity_error = float(np.max(np.abs(np.linalg.eigvalsh(dense_independent(L, J, h)) - np.sort(values))))
    assert parity_error < 1e-10
    e0 = min(values)
    ising_error = abs(e0 + 2 / np.sin(np.pi / (2 * L)))
    assert ising_error < 1e-10
    record(dict(kind='check', L=L, spectral_error=error, hermiticity_error=herm,
                intertwining_error=intertwine, parity_error=parity_error,
                exact_ising_energy_error=ising_error))


def summarize():
    """Summarize only this script's own corrected output, without external data."""
    records = [json.loads(line) for line in OUTPUT.read_text().splitlines() if line.strip()]
    records = [r for r in records if r.get('code_version') == 2]
    ground = {}
    spectra = {}
    def key(r):
        return (r['model'], r['D'], r['field'], r.get('tilt', 1. if r['model'] == 'generic' else 0.), r['L'])
    for r in records:
        if r['kind'] in ['ground', 'sweep']:
            ground[key(r)] = r
        elif r['kind'] == 'spectrum':
            spectra[key(r) + (r['parity'], r['m'])] = r
    groups = {}
    for k, r in ground.items():
        groups.setdefault(k[:-1], []).append(r)
    output = dict(calibrations={}, families=[], checks=[r for r in records if r['kind'] == 'check'],
                  crossings=[r for r in records if r['kind'] == 'crossing_result'],
                  crossing_dispersion=[r for r in records if r['kind'] == 'crossing_dispersion'])
    lines = []
    for k, rows in sorted(groups.items()):
        rows.sort(key=lambda r: r['L'])
        L = np.array([r['L'] for r in rows], float)
        E = np.array([r['energy'] for r in rows])
        S = np.array([r['entropies'][str(r['L'] // 2)] for r in rows])
        steps = [None] + (3 * np.diff(S) / np.diff(np.log(L))).tolist()
        family = dict(model=k[0], D=k[1], field=k[2], tilt=k[3], rows=[])
        lines.append(f'\nmodel={k[0]} D={k[1]} field={k[2]} tilt={k[3]}')
        lines.append(' L             E0          S_half   c_chord     c_step  parity  momentum')
        for r, step in zip(rows, steps):
            row = dict(L=r['L'], energy=r['energy'], S_half=r['entropies'][str(r['L']//2)],
                       c_chord=r['c_chord'], c_step=step, parity=r['parity'], momentum=r['m'])
            family['rows'].append(row)
            lines.append(f"{r['L']:2d} {r['energy']:16.10f} {row['S_half']:11.8f} "
                         f"{r['c_chord']:9.6f} {step if step is not None else float('nan'):10.6f} "
                         f"{r['parity']:7d} {r['m']:9d}")
        if len(L) >= 3:
            A = np.column_stack([np.ones(len(L)), L**-2, L**-4])
            coeff = np.linalg.lstsq(A, E/L, rcond=None)[0]
            family['naive_energy_cv_fit'] = float(-6 * coeff[1] / np.pi)
            family['energy_fit_warning'] = 'Valid only with conformal scaling and controlled zero-mode shifts.'
            family['half_entropy_c_fit'] = float(3 * np.linalg.lstsq(
                np.column_stack([np.ones(len(L)), np.log(L), L**-2]), S, rcond=None)[0][1])
        if k[0] in ['ising', 'xx']:
            velocity = 2. if k[0] == 'ising' else 4.
            output['calibrations'][k[0]] = dict(c_energy=family['naive_energy_cv_fit']/velocity,
                                               c_half=family['half_entropy_c_fit'])
        if k[0] in ['ising', 'residual'] and k[1] < .2:
            towers = []
            for r in rows:
                N = r['L']
                base = key(r)
                required = [(0, 0), (1, 0), (1, 1), (1, N-1), (0, 2), (0, N-2)]
                if not all(base + a in spectra for a in required):
                    continue
                t = {a: spectra[base + a]['energies'] for a in required}
                e0, eo = t[0, 0][0], t[1, 0][0]
                vp = N/(2*np.pi)*(t[1, 1][0]-eo)
                vm = N/(2*np.pi)*(t[1, N-1][0]-eo)
                vb = (vp+vm)/2
                towers.append(dict(L=N, v_plus=vp, v_minus=vm,
                    x_sigma=N*(eo-e0)/(2*np.pi*vb), x_epsilon=N*(t[0, 0][1]-e0)/(2*np.pi*vb),
                    stress_plus_ratio=N*(t[0, 2][0]-e0)/(4*np.pi*vp),
                    stress_minus_ratio=N*(t[0, N-2][0]-e0)/(4*np.pi*vm)))
            family['ising_tower_test'] = towers
        output['families'].append(family)
    output['spectrum_blocks'] = len(spectra)
    output['max_dimension'] = max((r['dim'] for r in spectra.values()), default=0)
    output['max_eigenvector_residual'] = max((r['residual'] for r in spectra.values()), default=0)
    output['sweep_records'] = sum(r['kind'] == 'sweep' for r in records)
    Path('c6_summary.json').write_text(json.dumps(output, indent=2) + '\n')
    Path('c6_tables.txt').write_text('\n'.join(lines) + '\n')
    print(json.dumps({k:v for k,v in output.items()
                      if k not in ['families','crossings','crossing_dispersion']}, indent=2))


def plot_results():
    """Standalone scientific figure, using only c6_summary.json generated here."""
    os.environ['MPLCONFIGDIR'] = str(Path('c6_mplconfig').resolve())
    os.environ['XDG_CACHE_HOME'] = str(Path('c6_cache').resolve())
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    summary = json.loads(Path('c6_summary.json').read_text())
    specifications = [
        ('ising', 0., 1., 0., 'Critical Ising'),
        ('xx', 0., 0., 0., 'XX'),
        ('residual', .1, 1.9891, 0., 'Interacting Ising candidate'),
        ('residual', .4, 1.2, 0., 'Chiral, Z2'),
        ('residual', .4, 2.05, 0., 'Dilute candidate, Z2'),
        ('generic', .4, 1.2, 1., 'No internal symmetry')]
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.3), constrained_layout=True)
    for model, D, field, tilt, label in specifications:
        group = next(f for f in summary['families'] if (f['model'], f['D'], f['field'], f['tilt']) == (model,D,field,tilt))
        rows = group['rows']
        L = np.array([r['L'] for r in rows])
        S = np.array([r['S_half'] for r in rows])
        color = axes[0].plot(L, [r['c_chord'] for r in rows], 'o-', label=label, ms=4)[0].get_color()
        axes[1].plot(np.log(L/L[0]), S-S[0], 'o-', color=color, ms=4)
    axes[0].axhline(1, color='0.5', ls=':', lw=1)
    axes[0].axhline(.5, color='0.7', ls=':', lw=1)
    axes[0].set(xlabel='Chain length L', ylabel='Chord-fit estimate', title='Entropy shape at a fixed size', xticks=[12,16,18,20,22])
    x = np.linspace(0, np.log(22/12), 100)
    axes[1].plot(x, x/3, 'k--', lw=1, label='c = 1 slope')
    axes[1].plot(x, x/6, 'k:', lw=1, label='c = 1/2 slope')
    axes[1].set(xlabel='log(L / smallest L)', ylabel='Change in half-chain entropy', title='Entropy growth across sizes')
    axes[0].legend(fontsize=8, loc='lower left', bbox_to_anchor=(.015, .12))
    axes[1].legend(fontsize=8, loc='best')
    fig.savefig('c6_entropy.png', dpi=180)
    fig.savefig('c6_entropy.svg')
    plt.close(fig)
    print('Wrote c6_entropy.png and c6_entropy.svg')


